#!/usr/bin/env python3
"""Compile lang/<code>.tsv (English<TAB>translation) into src/Generated/L10n<Code>.cs.
Checks every entry: tab-separated, no duplicate English keys, placeholders {0}.. kept."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
bad = 0
for tsv in sorted((root / "lang").glob("*.tsv")):
    code = tsv.stem
    seen, out, name = {}, [], code
    m = re.search(r"^# name: (.+)$", tsv.read_text(encoding="utf-8"), re.M)
    if m: name = m.group(1).strip()
    for n, line in enumerate(tsv.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            out.append(line); continue
        if line.count("\t") != 1:
            print(f"{tsv.name}:{n}: need exactly one TAB"); bad += 1; continue
        en, to = line.split("\t")
        if en in seen:
            print(f"{tsv.name}:{n}: duplicate of line {seen[en]}: {en[:60]}"); bad += 1; continue
        seen[en] = n
        ph_en = sorted(set(re.findall(r"\{(\d)(?:[,:][^}|]*)?\}", en)))
        ph_to = sorted(set(re.findall(r"\{(\d)(?:[,:][^}|]*)?(?:\|[^}]*)?\}", to)))
        if to and ph_en != ph_to:
            print(f"{tsv.name}:{n}: placeholders differ {ph_en} vs {ph_to}: {en[:60]}"); bad += 1
        out.append(line)
    body = "\n".join(out).replace('"', '""')
    cls = "L10n" + code.capitalize()
    cs = ("// GENERATED by tools/gen_l10n.py from lang/%s.tsv — edit the .tsv, then run the script.\n"
          "namespace ArchTweaker\n{\n    public static class %s\n    {\n        public const string Name = \"%s\";\n        public const string Table = @\"%s\n\";\n    }\n}\n") % (code, cls, name.replace('"', ''), body)
    (root / "src" / "Generated" / (cls + ".cs")).write_text(cs, encoding="utf-8")
    print(f"{tsv.name}: {len(seen)} entries -> src/Generated/{cls}.cs")
sys.exit(1 if bad else 0)
