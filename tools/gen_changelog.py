#!/usr/bin/env python3
"""Writes src/Generated/Changelog.cs from docs/CHANGELOG.md, for the What's new / version history dialog.

Usage: python3 tools/gen_changelog.py
A section starts with a version heading and runs to the next "## " line. Version headings:
  "## 3.19.0: <title>", "## 3.6.3", "## 2.4 / 2.4.1: <title>", "## What's new in 1.7: <title>", "## What's new in 1.4"
Old "What's new in X" headings are written as "## X: <title>", so every section has the same shape.
Changelog.Text = the newest 6 sections (kept for the tests); Changelog.All = every version, newest first.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEAD = re.compile(r"^## (?:What's new in )?(\d+\.\d+(?:\.\d+)?(?: / \d+\.\d+(?:\.\d+)?)?)(?::\s*(.*))?\s*$")

with open(os.path.join(ROOT, "docs", "CHANGELOG.md"), encoding="utf-8") as f:
    lines = f.read().split("\n")

sections, cur = [], None
for line in lines:
    if line.startswith("## "):
        if cur is not None:
            sections.append(cur)
        m = HEAD.match(line)
        cur = ["## " + m.group(1) + (": " + m.group(2) if m.group(2) else "")] if m else None
        continue
    if cur is not None:
        cur.append(line)
if cur is not None:
    sections.append(cur)


def lit(sects):
    text = "\n\n".join("\n".join(s).strip() for s in sects).strip() + "\n"
    return text.replace('"', '""')   # C# verbatim string


out = os.path.join(ROOT, "src", "Generated", "Changelog.cs")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_changelog.py from docs/CHANGELOG.md. Do not edit by hand.\n")
    f.write("namespace ArchTweaker\n{\n    public static class Changelog\n    {\n")
    f.write('        public const string Text = @"' + lit(sections[:6]) + '";\n')
    f.write('        public const string All = @"' + lit(sections) + '";\n')
    f.write("    }\n}\n")
print("Changelog.cs: %d version section(s)" % len(sections))
